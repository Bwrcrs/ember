// ============================================================
//  PlatformWin32 —— 窗口、键盘、声音（唯一碰 Win32 的地方）
//
//  ★ 这是整个项目里**唯一**真·平台层的文件。它做四件事：
//
//      1. 开一个窗口
//      2. 把 64x32 的显存放大贴上去
//      3. 把物理键盘的按键翻译成 CHIP-8 的 16 键
//      4. 声音定时器在走的时候响蜂鸣器
//
//    虚拟机内核完全不知道这个文件的存在。内核只管往 Display
//    里写点、把 keypad_ 的某一位设成 true，剩下的都是这里的事。
//
//  ★ 它整个包在 #ifdef EMBER_GUI 里。
//    不定义这个宏时（build.bat headless），runWithWindow 变成
//    一个明确的报错，而 screen / trace / asm / dis / selftest
//    照常工作。**测试永远跑在 headless 版本上**——
//    这不是省事，是必须：测试要能在没有桌面会话的环境里跑，
//    而且一个会弹窗的测试套件根本没法自动化。
//
//  ★ 分工：
//    setupConsole()  把控制台切到 UTF-8（和 Nova/Acorn 里那个一样）。
//                    注意它在**两个分支里都有实现**，因为
//                    headless 版本也要能正确打印中文。
//    runWithWindow() 开窗口跑，直到用户关掉窗口。
// ============================================================

#pragma once

#include <string>
#include <vector>

class Machine;

// 把控制台的输入输出都切到 UTF-8。
// Windows 的控制台默认不是 UTF-8，不切的话中文全是乱码。
// 非 Windows 平台上是个空操作。
//
// 【为什么它在平台层而不是 main.cpp】
// 在 Nova 和 Acorn 里，这一句是 main.cpp 里唯一的 <windows.h>，
// 而 Ember 的规矩是 main.cpp 必须零 Win32——
// 因为 lint 只放行 *_win32.* 和 utf8path.*。
// 把这几行挪进来，main.cpp 就干净了。
void setupConsole();

// 取命令行参数，**每个都是 UTF-8**。
//
// ★ 为什么不能用 main 的 argv？
//   因为 argv 是系统 ANSI 代码页的（这台机器上是 GBK），
//   而程序内部一路是 UTF-8。中间没有转换的话，
//   命令行上传一个中文 ROM 路径就会乱码、打不开文件，
//   而且**不一定报错**——乱码碰巧解成一个合法文件名的话，
//   你打开的是另一个文件。
//
//   所以 main() 用这个函数，不用 argv。
//   返回值第 0 个元素是程序自己的路径，和 argv[0] 一样。
//   Windows 上它是用宽字符 API 绕开代码页拿到的；
//   其他平台返回空（那边 argv 本来就是字节串，直接用即可）。
std::vector<std::string> commandLineArgs();

// 开窗口跑机器，直到窗口被关掉。返回进程退出码（0 正常）。
//
//   ips    每秒指令数，默认 700
//   hz     定时器频率，默认 60
//   scale  画面放大倍数，0 表示"按窗口大小自动算"
//
// headless 构建里这个函数直接返回 2 并打印一句说明。
int runWithWindow(Machine& machine, int ips, int hz, int scale);

// ============================================================
//  二、在终端里玩（不弹窗口，就用这个控制台）
// ============================================================
//
//  ★ 为什么终端版和窗口版是两个东西，而不是先凑合一个
//
//    阶段 6 的目标是"能玩"。要做到能玩，需要三件平台能力：
//    开 ANSI 转义、按一个键立刻拿到（不用回车）、量真实时间。
//    这三件事在终端里和在窗口里是**完全不同的 API**，
//    没有任何一行能复用。
//
//    但**内核一行都不用改**——机器还是那台机器，
//    只是把它那块 64x32 显存画到终端里而不是窗口里。
//    这正是"内核不碰平台"这条线换来的东西：
//    换一个前端不需要动内核一个字节。
//
//  ★ 下面这些函数**全部**是 Win32 的。main.cpp 只调它们，
//    所以 main.cpp 到现在仍然是零 Win32 的。

// 一次按键事件。
struct KeyEvent {
    // 0..15 是 CHIP-8 的键号。KEY_QUIT 表示"用户想退出"。
    int key;
    bool down;  // true = 按下，false = 松开
};

// 用户按了 Esc。它不是 CHIP-8 的键（CHIP-8 只有 0-F），
// 所以借它当"我不玩了"。
constexpr int KEY_QUIT = -1;

// 打开终端的 ANSI 转义支持（Windows 管这个叫 VT）。
//
// 返回 false 表示这个终端**画不了**。调用方应该据此拒绝启动，
// 并且用 terminalAnsiFailureReason() 把具体原因告诉用户——
// 不要自己猜一个原因。
//
// 【为什么必须显式开】Windows 的控制台不是天生认 ANSI 的。
// 不开的话那些 "\x1b[97m" 会**原样打出来**，
// 屏幕上一片 "[97m[107m▀" 的乱码，而且看起来像是渲染器的 bug。
bool enableTerminalAnsi();

// enableTerminalAnsi() 返回 false 时，具体是为什么。
// 只有在它返回 false 之后调才有意义。
//
// ★ 存在的理由：能画出不来有好几种原因，而它们的**解法完全不同**：
//     输出被重定向   -> 别重定向
//     在 Git Bash 里 -> 换 cmd / PowerShell，或者用 winpty 包一层
//     Windows 太老   -> 没辙，用 screen 看画面
//   笼统报一句"你的终端不支持 ANSI"会把用户送去查错的地方。
std::string terminalAnsiFailureReason();

// 终端窗口有多少列 / 多少行。不是控制台（被重定向了）时返回 0。
//
// 用它来判断"64 列的半块画面放不放得下"，
// 而不是假设窗口一定够大——用户随时可以把窗口拖小。
int terminalColumns();
int terminalRows();

// 从系统启动到现在过了多少毫秒。只用来量"两帧之间过了多久"。
//
// 【为什么不用 std::chrono】可以，但没必要：Windows 上
// GetTickCount64 就是这个用途的专用函数，分辨率 1ms 足够，
// 而且不会因为系统时间被改（对时、夏令时）而跳变。
double nowMs();

// 睡一会儿。为了把帧率压到 60Hz 左右，不然 CPU 会跑满一个核。
void sleepMs(int ms);

// ---- 进入 / 退出"终端游戏模式" ----
//
// beginTerminalInput 会备份控制台当前的输入模式，然后改成：
//   * 按一个键立刻送到程序（关掉行缓冲，不然要按回车）
//   * 按键不回显（不然屏幕上一堆字符把画面顶掉）
//   * 关掉 QuickEdit
//   * Ctrl+C 不再当信号，而是当作一个普通按键交给我们
//
// endTerminalInput 把上面这些**原样还原**。
//
// 【为什么还原是必须的，不是讲卫生】
// 行缓冲和回显是**控制台**的属性，不是进程的。跑完游戏不还原，
// 回到命令行之后用户敲什么都看不见、还得按回车——
// 而且他完全不知道为什么，只会觉得"这个终端坏了"。
//
// 【QuickEdit 为什么必须关】它开着的时候，在窗口里点一下鼠标
// 就开始框选，**整个程序会阻塞**直到你按一下键或 Esc。
// 现象是"模拟器卡死了"，实际是控制台在等用户选完。
// 这个坑极常见，而且不知道的人会去查模拟器的性能。
//
// 返回 false 表示**标准输入不是控制台**（被重定向了），
// 于是一个按键也收不到。调用方必须据此拒绝启动——
// 不然用户会进入一个按什么都没反应、只能关窗口的游戏，
// 而且关窗口那条路径还会把控制台留在替代屏幕里。
bool beginTerminalInput();
void endTerminalInput();

// 把攒着的按键**全部**取出来，不阻塞。
//
// 不是"取一个"：一帧里可能按下又松开好几个键，
// 只取一个的话剩下的会积压到下一帧，手感变成慢半拍。
std::vector<KeyEvent> pollKeyEvents();
