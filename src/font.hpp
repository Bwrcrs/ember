// ============================================================
//  Font —— 十六进制数字的字模
//
//  CHIP-8 机器里本身不带任何"字符"概念，它只会画精灵。
//  但是 Fx29 这条指令要求机器能"把数字 n 的字模地址给我"，
//  于是这 16 个数字的图形必须**烧在机器内存里**。
//
//  16 个数字 × 每个 5 字节 = 80 字节。这就是整张字体表。
//
//  ★ 为什么叫"4x5"字体，明明一个精灵是 8 像素宽？
//    因为字模只用每个字节的**高 4 位**，也就是只占 8 列里的左边 4 列。
//    右边 4 位永远是 0。所以实际图形是 4 宽 5 高。
//
//  看一眼就懂，比如 '0'：
//      0xF0  =  1111 0000
//      0x90  =  1001 0000
//      0x90  =  1001 0000
//      0x90  =  1001 0000
//      0xF0  =  1111 0000
//    画出来就是：
//      ####
//      #  #
//      #  #
//      #  #
//      ####
//
//  【一个 C++ 上的坑】为什么是 inline constexpr 而不是 constexpr？
//  在命名空间作用域，光写 constexpr 的变量是**内部链接**的，
//  意思是每个 #include 这个头文件的 .cpp 都会拿到**自己的一份拷贝**。
//  拷贝 80 字节不心疼，但地址不同，将来想比指针就会出事。
//  加上 inline（C++17 的 inline 变量）就变成外部链接、全程序一份定义，
//  这才是"一张共享的表"该有的样子。
//
//  这个文件是 header-only 的。
// ============================================================

#pragma once

#include <array>
#include <cstdint>

// 经典 CHIP-8 字体：16 个十六进制数字，每个 5 字节，共 80 字节。
inline constexpr std::array<std::uint8_t, 80> FONT = {
    0xF0, 0x90, 0x90, 0x90, 0xF0,  // 0
    0x20, 0x60, 0x20, 0x20, 0x70,  // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0,  // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0,  // 3
    0x90, 0x90, 0xF0, 0x10, 0x10,  // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0,  // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0,  // 6
    0xF0, 0x10, 0x20, 0x40, 0x40,  // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0,  // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0,  // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90,  // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0,  // B
    0xF0, 0x80, 0x80, 0x80, 0xF0,  // C
    0xE0, 0x90, 0x90, 0x90, 0xE0,  // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0,  // E
    0xF0, 0x80, 0xF0, 0x80, 0x80,  // F
};

inline constexpr int FONT_GLYPH_COUNT = 16;
inline constexpr int FONT_GLYPH_BYTES = 5;
inline constexpr int FONT_TOTAL_BYTES = FONT_GLYPH_COUNT * FONT_GLYPH_BYTES;

// 取第 digit 个字模的起始地址（指向 FONT 数组里面）。
//
// 【注意】这里**没有**对 digit 做范围检查，而是 & 0x0F。
// 这是故意的：Fx29 的调用方已经在按 quirks 决定"取低半字节还是整个字节"，
// 传进来的一定是 0..15。这里再夹一次只是防御性的第二道锁，
// 保证无论调用方怎么错，返回的指针都落在 FONT 这 80 字节之内
// ——宁可取错字模，也不能越界读。
//
// base 是字模在机器内存里的起始地址（0x050 或 0x000，见 Quirks）。
// 这里不需要 base，因为返回的是**表内偏移**，由调用方加上 base。
inline const std::uint8_t* fontSprite(std::uint8_t digit) {
    return FONT.data() + FONT_GLYPH_BYTES * (digit & 0x0F);
}
