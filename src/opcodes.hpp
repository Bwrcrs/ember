// ============================================================
//  Opcodes —— 指令的"名字"，以及把 16 位数字变成名字的那一步
//
//  ★ 这个文件是整个项目**唯一一份**指令表。
//    反汇编器（读名字）、汇编器（写名字）、cpu.cpp（执行名字）、
//    selftest（检查三者一致）全部从这里取。
//    如果允许第二份，两份迟早会对不上，而对不上的表现是
//    "反汇编出来的东西汇编不回去"——这种 bug 特别难定位。
//
//  CHIP-8 的一条指令就是一个 16 位大端整数。没有变长编码，
//  没有前缀，没有 ModRM 那一套。整个指令集只有 35 条。
//
//  16 位的结构（这是理解一切的基础）：
//
//      nnn   = 最低 12 位，一个内存地址
//      nn    = 最低 8 位，一个立即数
//      n     = 最低 4 位，一个半字节
//      x     = 第 8-11 位，寄存器号 Vx
//      y     = 第 4-7 位，寄存器号 Vy
//
//      ┌───┬───┬───┬───┐
//      │ 高半字节 │ x │ y │ n │
//      └───┴───┴───┴───┘
//        15..12  11..8  7..4  3..0
//
//  高半字节决定指令类别，剩下的 12 位怎么解释由类别决定。
//
//  【译码策略：为什么先归约成枚举，再对枚举 switch】
//
//  备选方案有四种，逐一说清为什么否掉：
//
//   (a) 对 16 位全值写 switch —— 要 4096 个 case，或者用 GCC 的
//       "case 0x1000 ... 0x1FFF:" 区间扩展。本项目内核坚持纯标准 C++，
//       所以不行。
//
//   (b) 严格嵌套 switch（先高半字节，再低半字节）—— 对 0x0、0xE、0xF
//       这三类，内层其实必须按**低字节**分派，于是形状变得不一致；
//       而 8xy4 这种"要半字节当选择器、还要两个寄存器"的指令
//       会被埋到第四层。
//
//   (c) 16 个函数指针表 —— 只是在学习的人最想单步跟进的地方
//       加了一层间接，并没有消除嵌套，那 16 个小函数里有 14 个
//       还是各含一个只有一两个 case 的 switch。
//
//   (d) 35 条"掩码 + 匹配值"的表 —— 看起来最优雅，而且这张表
//       还能直接喂给反汇编器和汇编器。但**条目的顺序变成了语义**：
//       5xy0 只在 n == 0 时成立，所以条目必须写成 {0xF00F, 0x5000}，
//       这个掩码很容易写错，而写错的后果是**静默译错**，不是编译报错。
//       Annn / Bnnn / 1nnn 都想匹配 {0xF000, ...}，顺序一动就悄悄坏掉。
//       调试一张数据结构比调试一段会跑的代码难得多。
//
//   所以选：decode() 用嵌套 switch 归约成 enum，
//   cpu.cpp 对 enum 做**扁平 switch 且不写 default:**
//   —— 这样 -Wswitch 会点名任何一个"加了枚举值但忘了实现"的指令。
//   在 700Hz 这个速度下，译码开销完全不值一提，可以忽略。
//
//  ★ 一个必须记住的结构性事实：**Fx__ 家族只能按低字节分派，不能按低半字节。**
//    因为 Fx15（LD DT, Vx）和 Fx55（LD [I], Vx）的低半字节**都是 5**。
//    只有 8xy_ 是真正的单半字节家族。
//    这个区别决定了 decodeMisc 的 switch 必须写 (raw & 0xFF)。
// ============================================================

#pragma once

#include <cstdint>
#include <string>

enum class Opcode {
    // ---- 0x0 开头：系统 ----
    SYS,        // 0nnn  调用机器码子程序。现代模拟器一律忽略（当空操作）
    CLS,        // 00E0  清屏
    RET,        // 00EE  从子程序返回

    // ---- 跳转和调用 ----
    JP,         // 1nnn  PC = nnn
    CALL,       // 2nnn  压栈，PC = nnn

    // ---- 条件跳过（比较立即数） ----
    SE_BYTE,    // 3xnn  Vx == nn 则跳过下一条
    SNE_BYTE,   // 4xnn  Vx != nn 则跳过下一条

    // ---- 寄存器赋值和运算（立即数） ----
    LD_BYTE,    // 6xnn  Vx = nn
    ADD_BYTE,   // 7xnn  Vx += nn（**不**影响 VF，这条和 8xy4 不一样）

    // ---- 寄存器之间的运算（8xy_ 家族） ----
    LD_REG,     // 8xy0  Vx = Vy
    OR,         // 8xy1  Vx |= Vy
    AND,        // 8xy2  Vx &= Vy
    XOR,        // 8xy3  Vx ^= Vy
    ADD_REG,    // 8xy4  Vx += Vy，进位进 VF
    SUB,        // 8xy5  Vx -= Vy，借位进 VF
    SHR,        // 8xy6  Vx >>= 1，移出的位进 VF
    SUBN,       // 8xy7  Vx = Vy - Vx，借位进 VF
    SHL,        // 8xyE  Vx <<= 1，移出的位进 VF

    // ---- 条件跳过（比较寄存器） ----
    SE_REG,     // 5xy0  Vx == Vy 则跳过
    SNE_REG,    // 9xy0  Vx != Vy 则跳过

    // ---- 内存和随机数 ----
    LD_ADDR,    // Annn  I = nnn
    JP_V0,      // Bnnn  PC = nnn + V0（或 + Vx，见 Quirks）
    RND,        // Cxnn  Vx = 随机数 & nn

    // ---- 显示 ----
    DRW,        // Dxyn  在 (Vx, Vy) 画 n 行精灵，碰撞进 VF

    // ---- 键盘 ----
    SKP,        // Ex9E  Vx 对应的键按着则跳过
    SKNP,       // ExA1  Vx 对应的键没按则跳过

    // ---- 定时器 ----
    LD_VX_DT,   // Fx07  Vx = 延迟定时器
    LD_VX_K,    // Fx0A  Vx = 等一个按键（**阻塞**）
    LD_DT_VX,   // Fx15  延迟定时器 = Vx
    LD_ST_VX,   // Fx18  声音定时器 = Vx

    // ---- 内存（I 寄存器相关） ----
    ADD_I_VX,   // Fx1E  I += Vx
    LD_F_VX,    // Fx29  I = 字模里 Vx 那个数字的地址
    LD_B_VX,    // Fx33  把 Vx 的十进制三位写进 [I]
    LD_I_VX,    // Fx55  把 V0..Vx 存进内存
    LD_VX_I,    // Fx65  从内存读进 V0..Vx

    // ---- 不是合法指令 ----
    UNKNOWN
};

// 一条指令译码之后的样子。
//
// 【设计取舍】用"标签 + 字段"的平坦结构体，不用 std::variant。
// 和 Nova / Acorn 的理由一模一样：std::visit 漏写一个分支会喷
// 四十行模板内部报错，而这里漏写字段顶多是字段没用到。
// 而且这些字段（x/y/n/nn/nnn）是**从 16 位里切出来的，天然共存**，
// 不是互斥的几种情况——硬套 variant 反而别扭。
struct Decoded {
    std::uint16_t raw = 0;                 // 原始 16 位
    Opcode op = Opcode::UNKNOWN;
    std::uint8_t x = 0;                    // 寄存器号 Vx，0..15
    std::uint8_t y = 0;                    // 寄存器号 Vy，0..15
    std::uint8_t n = 0;                    // 低半字节，0..15
    std::uint8_t nn = 0;                   // 低字节，0..255
    std::uint16_t nnn = 0;                 // 低 12 位，0..4095
};

// 把 16 位数字译码。永远返回一个结果，认不出来就是 Opcode::UNKNOWN。
// 这个函数不抛异常——因为 CPU 每秒钟要调用它 700 次，
// 而且"读到不认识的指令"是程序跑飞时的正常现象，不是异常情况。
Decoded decode(std::uint16_t raw);

// 这个枚举值是不是一条真实存在的指令（UNKNOWN 不是）。
bool isDefined(Opcode op);

// 指令的助记符，比如 "LD Vx, byte"。反汇编器和 trace 输出用。
const char* opcodeName(Opcode op);
