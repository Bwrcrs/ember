// ============================================================
//  RenderAnsi —— 把 64x32 显存画到终端里
//
//  这个文件是**纯标准 C++**：它只生成字符串，不碰控制台。
//  真正把字符串写出去的是调用方（main.cpp）。
//  这样渲染逻辑本身可以被测试——不然"画出来的东西对不对"
//  就只能靠眼睛看，而那正是要避免的。
//
//  ★ 为什么是"半块"而不是"一个像素一个字符"？
//
//    64x32 一个像素一个字符要 32 行。这台机器的控制台窗口只有 30 行，
//    放不下 → 每画一帧就滚一行 → 画面自己往上爬，根本没法看。
//
//    但终端里有个字符叫"上半块" ▀ (U+2580)：
//    它的**上半格**涂前景色，**下半格**涂背景色。
//    于是一个字符格子能装**上下两个像素**，64x32 变成 64x16，
//    16 行放进 30 行的窗口绰绰有余，还能留一行写状态。
//
//    这也是终端里画图的标准做法，不是这里的独门技巧。
//
//  ★ 颜色是"能省就省"的。
//
//    一帧 1024 个格子，每格都发一遍颜色转义序列的话，
//    输出会大好几倍——而窗口版每秒要画 60 帧。
//    所以记着"当前前景/背景是什么"，只在变的时候才发转义。
//    屏幕大部分是黑的，那一大片就只剩空格，字节数很小。
// ============================================================

#pragma once

#include <string>

class Display;

namespace ansi {

// ---- 控制序列 ----
// 都是 const char*，直接 fputs 用。

// 进/出"替代屏幕缓冲"。进去之后画面不会滚进滚动历史，
// 退出时原来命令行里的内容原样回来。
// 用这个而不是"清屏"，是因为清屏会把用户之前的输出抹掉。
extern const char* ENTER_ALT_SCREEN;
extern const char* LEAVE_ALT_SCREEN;

// 藏/显光标。不藏的话光标会在画面上闪。
extern const char* HIDE_CURSOR;
extern const char* SHOW_CURSOR;

// 光标归位到左上角。重绘时用它盖掉上一帧，不滚屏。
extern const char* HOME;

// 清屏并归位。
extern const char* CLEAR;

// 复位所有属性（颜色等）。
extern const char* RESET;

// ---- 渲染 ----
//
// 半块模式：64 列 x 16 行。
//
//   color == true   用 ANSI 颜色：亮的像素涂白，灭的涂黑。
//                   需要终端支持转义序列（Windows 上要开 VT）。
//   color == false  不用颜色，任何一半亮就画 '#'。
//                   没有颜色的终端也能看出图案，只是粗一档。
//
// 返回值是**一整屏的文本**，行尾是 "\n"（除了最后一行）。
// 不自带光标归位——调用方自己决定要不要先发 HOME。
//
// ★ 行尾只写 "\n"，**不要**写成 "\r\n"。
//   标准输出是文本模式，CRT 会把 "\n" 自动翻成 "\r\n"。
//   自己再写一个 "\r" 就变成 "\r\r\n"，而 tests\run_tests.ps1
//   的 Normalize 是先把 "\r\n" 换成 "\n"、再把剩下的 "\r"
//   换成 "\n"——于是 "\r\r\n" 会变成**两个**换行，
//   黄金文件里凭空多出一行空行。项目里所有输出都只写 "\n"。
std::string renderHalfBlock(const Display& display, bool color);

// 纯 ASCII 模式：一个像素一个字符，64x32，'#' 和 ' '。
//
// 这个是给"终端不支持 ANSI"兜底的，需要把窗口拉到 33 行以上
// 才不会滚屏。日常应该用 renderHalfBlock。
std::string renderAscii(const Display& display);

}  // namespace ansi
